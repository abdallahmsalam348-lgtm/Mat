// Order of precedence: Gradle -P property > environment variable > matchly.properties
val matchlyProps = Properties().apply {
    val f = rootProject.file("matchly.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

fun config(name: String): String {
    val fromProp = (project.findProperty(name) as String?)?.trim().orEmpty()
    if (fromProp.isNotEmpty()) return fromProp
    val fromEnv = System.getenv(name)?.trim().orEmpty()
    if (fromEnv.isNotEmpty()) return fromEnv
    return matchlyProps.getProperty(name, "").trim()
}

